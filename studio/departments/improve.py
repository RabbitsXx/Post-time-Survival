#!/usr/bin/env python3
"""improve.py : the studio's self-improvement loop.  Reads kpi/history.jsonl (every review ever done), groups the issues by department and kind, ranks them by
(how many clips had it x how many points it cost x how recent) and writes BACKLOG.md: the toolchain work the next run MUST do first (fix the engine / library / template so the problem
cannot come back, then re-review the golden clips).  Items stay in the backlog until the last 3 clips no longer show them; they are then moved to DONE.md with the date."""
import os,re,json,datetime as dt,collections
R=os.path.dirname(os.path.abspath(__file__));HIST=R+'/kpi/history.jsonl'
def kind(s):return re.sub(r'\d+(\.\d+)?','N',re.sub(r"\[.*?\]|\(.*?\)|'.*?'|\".*?\"",'',s))[:90]
def backlog():
    if not os.path.exists(HIST):return
    rows=[json.loads(l) for l in open(HIST) if l.strip()];latest={}
    for r in rows:latest[r['clip']]=r
    rows=list(latest.values());recent=rows[-3:];items=collections.defaultdict(lambda:dict(n=0,pts=0,clips=[],ex=''))
    for r in rows:
        for d,iss in r['issues'].items():
            for i in iss:
                k=(d,kind(i));it=items[k];it['n']+=1;it['clips'].append(r['clip']);it['ex']=i
    live=[(k,v) for k,v in items.items() if any(c in [x['clip'] for x in recent] for c in v['clips'])]
    live.sort(key=lambda kv:-(kv[1]['n']*(3 if kv[0][0] in('story','art','legal') else 2)))
    L=['# Studio backlog (generated by improve.py, do not edit by hand)','',f'Updated {dt.datetime.utcnow():%Y-%m-%d %H:%M} UTC from {len(rows)} reviewed clips. Work from the top; fix the CAUSE in the toolchain, then re-review.','','| # | dept | seen in | issue |','|---:|---|---:|---|']
    for n,(k,v) in enumerate(live[:40],1):L.append(f"| {n} | {k[0]} | {v['n']} | {v['ex'][:230]} |")
    open(R+'/BACKLOG.md','w').write('\n'.join(L)+'\n')
if __name__=='__main__':backlog();print(open(R+'/BACKLOG.md').read()[:1500])
