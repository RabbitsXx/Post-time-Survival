#!/usr/bin/env python3
"""scene_catalog.py : scans the engine and writes SCENES.md - every scene name with the params / kinds / modes it understands.
(So a new story is written from a menu instead of by reading 100 KB of code.)"""
import os,re,sys
R=os.path.dirname(os.path.abspath(__file__));S=os.path.abspath(R+'/..');V=S+'/v3';sys.path.insert(0,R)
sys.path.insert(0,R);from render_part import split_blocks
files=[f for f in sorted(os.listdir(V)) if re.match(r'(lib_|kit)\w*\.js$',f) and 'backup' not in f]
cat={}
for f in files:
    for name,blk in split_blocks(open(f'{V}/{f}').read())[1].items():
        d=cat.setdefault(name,dict(file=f,params=set(),kinds=set(),modes=set(),doc=''))
        d['params']|=set(re.findall(r'\bp\.(\w+)',blk))-{'kind','mode'}
        d['kinds']|=set(re.findall(r"\bk==='(\w+)'",blk))|set(re.findall(r"\bk===\"(\w+)\"",blk));d['modes']|=set(re.findall(r"mode==='(\w+)'",blk))
    txt=open(f'{V}/{f}').read()
    for m in re.finditer(r'/\*[^*]*?(\w+)[^*]*?\*/\s*\nLIB\.(\w+)',txt):pass
out=['# Scene catalogue (generated by ser/scene_catalog.py)\n','Use in a script as `bt("scene",{params},role,caps,hud,sfx)`.  Keep key content inside x 40-680 and above y 740 (caption band 742-922); run `lint_layout.js` to check.\n',
     '| scene | file | kinds / modes | params |','|---|---|---|---|']
for n in sorted(cat):
    d=cat[n];km=', '.join(sorted(d['kinds']|d['modes'])) or '-';pr=', '.join(sorted(d['params'])) or '-'
    out.append(f"| `{n}` | {d['file']} | {km} | {pr} |")
open(f'{S}/SCENES.md','w').write('\n'.join(out)+'\n');print(f'{len(cat)} scenes -> SCENES.md')
